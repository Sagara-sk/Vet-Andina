ALTER TABLE turno
  ADD COLUMN IF NOT EXISTS duracion_minutos INTEGER NOT NULL DEFAULT 30;

UPDATE turno
SET duracion_minutos = 120
WHERE modalidad = 'RURAL' AND duracion_minutos = 30;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'turno_duracion_minutos_check'
  ) THEN
    ALTER TABLE turno
      ADD CONSTRAINT turno_duracion_minutos_check
      CHECK (
        (modalidad = 'CONSULTORIO' AND duracion_minutos = 30)
        OR (modalidad = 'RURAL' AND duracion_minutos BETWEEN 60 AND 120)
      );
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS agenda_disponibilidad_rural (
  id_disponibilidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_veterinario UUID NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  fecha_hora TIMESTAMPTZ NOT NULL,
  duracion_minutos INTEGER NOT NULL CHECK (duracion_minutos BETWEEN 60 AND 120),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_veterinario, fecha_hora)
);

CREATE TABLE IF NOT EXISTS agenda_feriado (
  fecha DATE PRIMARY KEY,
  motivo VARCHAR(150) NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS agenda_disponibilidad_rural_fecha_idx
  ON agenda_disponibilidad_rural (fecha_hora, id_veterinario);
