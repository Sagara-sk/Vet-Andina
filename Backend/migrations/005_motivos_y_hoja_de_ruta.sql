ALTER TABLE turno
  ADD COLUMN IF NOT EXISTS motivo_categoria VARCHAR(80),
  ADD COLUMN IF NOT EXISTS motivo_detalle VARCHAR(300);

UPDATE turno
SET motivo_detalle = motivo
WHERE motivo_detalle IS NULL
  AND motivo IS NOT NULL;

CREATE TABLE IF NOT EXISTS hoja_de_ruta (
  id_hoja_de_ruta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_veterinario UUID NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  fecha_hora_inicio TIMESTAMPTZ NOT NULL,
  fecha_hora_fin TIMESTAMPTZ NOT NULL,
  detalle VARCHAR(300),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT hoja_de_ruta_intervalo_check
    CHECK (fecha_hora_fin > fecha_hora_inicio)
);

CREATE INDEX IF NOT EXISTS hoja_de_ruta_veterinario_intervalo_idx
  ON hoja_de_ruta (id_veterinario, fecha_hora_inicio, fecha_hora_fin);
